CREATE TABLE IF NOT EXISTS profiles (
    user_id TEXT PRIMARY KEY,
    payload TEXT NOT NULL CHECK (jsonb_typeof(payload::jsonb) = 'object')
);
CREATE TABLE IF NOT EXISTS visits (
    user_id TEXT NOT NULL,
    visit_id TEXT NOT NULL,
    payload TEXT NOT NULL CHECK (jsonb_typeof(payload::jsonb) = 'object'),
    PRIMARY KEY (user_id, visit_id)
);
CREATE TABLE IF NOT EXISTS reviews (
    user_id TEXT NOT NULL,
    visit_id TEXT NOT NULL,
    hospital_id TEXT NOT NULL,
    payload TEXT NOT NULL CHECK (jsonb_typeof(payload::jsonb) = 'object'),
    review_order BIGINT GENERATED BY DEFAULT AS IDENTITY,
    PRIMARY KEY (user_id, visit_id)
);
CREATE INDEX IF NOT EXISTS reviews_hospital ON reviews(hospital_id, review_order DESC);
CREATE INDEX IF NOT EXISTS visits_hospital ON visits((payload::jsonb ->> 'hospitalId'));
CREATE TABLE IF NOT EXISTS facilities (
    id TEXT PRIMARY KEY,
    type TEXT NOT NULL,
    name TEXT NOT NULL,
    address TEXT NOT NULL,
    latitude DOUBLE PRECISION NOT NULL,
    longitude DOUBLE PRECISION NOT NULL,
    website TEXT NOT NULL,
    open TEXT NOT NULL,
    median_wait INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS facility_departments (
    facility_id TEXT NOT NULL,
    department TEXT NOT NULL,
    PRIMARY KEY (facility_id, department)
);
CREATE INDEX IF NOT EXISTS facilities_location_idx ON facilities(latitude, longitude);
CREATE INDEX IF NOT EXISTS departments_lookup_idx ON facility_departments(department, facility_id);
CREATE TABLE IF NOT EXISTS university_locations (
    school_id TEXT PRIMARY KEY,
    address TEXT NOT NULL,
    payload TEXT NOT NULL CHECK (jsonb_typeof(payload::jsonb) = 'object')
);
CREATE TABLE IF NOT EXISTS data_imports (
    kind TEXT PRIMARY KEY,
    imported_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
